#!/usr/bin/env python3
"""Generate vendor/alacritty_terminal/src/term/width_tables.rs.

Character widths follow jquast's wcwidth (MIT), the reference ucs-detect
measures terminals against. Regenerate after upgrading it:

    python3 -m venv /tmp/wc && /tmp/wc/bin/pip install wcwidth
    /tmp/wc/bin/python scripts/gen-width-tables.py
"""
import os
import subprocess
import wcwidth
from wcwidth.table_zero import ZERO_WIDTH
from wcwidth.table_wide import WIDE_EASTASIAN
from wcwidth.table_mc import CATEGORY_MC
from wcwidth.table_vs15 import VS15_WIDE_TO_NARROW
from wcwidth.table_vs16 import VS16_NARROW_TO_WIDE
from wcwidth.table_grapheme import (EXTENDED_PICTOGRAPHIC, GRAPHEME_REGIONAL_INDICATOR,
                                    ISC_INVISIBLE_STACKER, ISC_VIRAMA)

latest = max(ZERO_WIDTH, key=lambda v: tuple(map(int, v.split('.'))))


def merged(*tables):
    out = []
    for lo, hi in sorted(r for t in tables for r in t):
        if out and lo <= out[-1][1] + 1:
            out[-1][1] = max(out[-1][1], hi)
        else:
            out.append([lo, hi])
    return out


def table(name, doc, ranges):
    rows = "\n".join(f"    (0x{lo:05x}, 0x{hi:05x})," for lo, hi in ranges)
    return f"/// {doc}\npub(crate) static {name}: &[(u32, u32)] = &[\n{rows}\n];\n"


LIMIT = 0x20000  # the BMP and the SMP (emoji); above it the range tables answer


def lookup():
    """Two-level width table below LIMIT: 2 bits per code point (0 zero,
    1 narrow, 2 wide), in deduplicated blocks of 128 code points."""
    widths = bytearray([1]) * LIMIT
    for lo, hi in WIDE_EASTASIAN[latest]:
        for cp in range(lo, min(hi, LIMIT - 1) + 1):
            widths[cp] = 2
    for lo, hi in ZERO_WIDTH[latest]:  # zero wins, as in wcwidth()
        for cp in range(lo, min(hi, LIMIT - 1) + 1):
            widths[cp] = 0
    blocks, index = [], []
    for start in range(0, LIMIT, 128):
        packed = bytes(
            sum(widths[start + i + k] << (2 * k) for k in range(4)) for i in range(0, 128, 4))
        if packed not in blocks:
            blocks.append(packed)
        index.append(blocks.index(packed))
    assert len(blocks) <= 256
    rows = ",\n".join("    [" + ", ".join(str(b) for b in blk) + "]" for blk in blocks)
    return (f"/// Code points below this use the lookup table.\n"
            f"pub(crate) const WIDTH_LIMIT: u32 = 0x{LIMIT:x};\n"
            f"/// Block of each 128 code points below `WIDTH_LIMIT`.\n"
            f"pub(crate) static WIDTH_INDEX: [u8; {len(index)}] = "
            f"[{', '.join(map(str, index))}];\n"
            f"/// Widths, 2 bits per code point, low bits first.\n"
            f"pub(crate) static WIDTH_BLOCKS: [[u8; 32]; {len(blocks)}] = [\n{rows}\n];\n")


root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
path = os.path.join(root, "vendor/alacritty_terminal/src/term/width_tables.rs")
with open(path, "w") as f:
    f.write(f"// GENERATED by scripts/gen-width-tables.py from wcwidth "
            f"{wcwidth.__version__} (Unicode {latest}); do not edit.\n\n")
    f.write(table("ZERO", "Zero-width characters (combining marks, format characters).",
                  ZERO_WIDTH[latest]))
    f.write(table("WIDE", "East Asian Wide and Fullwidth characters.", WIDE_EASTASIAN[latest]))
    f.write(table("MC", "Spacing combining marks (General_Category Mc).", CATEGORY_MC[latest]))
    f.write(table("VS15_NARROWS", "Wide emoji that VS15 (U+FE0E) shows as text, one cell.",
                  VS15_WIDE_TO_NARROW["9.0.0"]))
    f.write(table("VS16_WIDENS", "Narrow characters that VS16 (U+FE0F) shows as emoji, two cells.",
                  VS16_NARROW_TO_WIDE["9.0.0"]))
    f.write(table("EXT_PICT", "Extended_Pictographic: emoji that ZWJ sequences join.",
                  EXTENDED_PICTOGRAPHIC))
    f.write(table("VIRAMA", "Indic viramas and invisible stackers: they join conjuncts.",
                  merged(ISC_VIRAMA, ISC_INVISIBLE_STACKER)))
    f.write(table("REGIONAL_INDICATOR", "Regional indicators: pairs form flags.",
                  GRAPHEME_REGIONAL_INDICATOR))
    f.write(lookup())
subprocess.run(["rustfmt", "--edition", "2024", path], check=True)
print(path)
